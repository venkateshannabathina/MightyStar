import Foundation

@main struct CheckCallReducer {
    static func main() {
        var call = CallState()
        call.apply(.start(sessionId: "s1", characterId: "c1"))
        call.apply(.start(sessionId: "s2", characterId: "c2"))
        precondition(call.sessionId == "s1" && call.lifecycle == .connecting, "double start")
        call.apply(.connected(sessionId: "s2"))
        precondition(call.lifecycle == .connecting, "stale ready")
        call.apply(.connected(sessionId: "s1"))
        call.apply(.userSpeechConfirmed)
        call.apply(.userSpeechEnded)
        call.apply(.commitUser(turnId: "t1", generation: 1))
        let old = CallState.Ticket(sessionId: "s1", characterId: "c1", generation: 1, turnId: "t1")
        call.apply(.speechBuffered(old))
        call.apply(.speechStarted(old))
        precondition(call.output == .playing)
        let effects = call.apply(.userSpeechConfirmed)
        precondition(effects.first == .stopOutput && call.output == .idle, "local interruption")
        call.apply(.speechBuffered(old))
        precondition(call.output == .idle, "old generation output")
        call.apply(.userSpeechEnded)
        call.apply(.commitUser(turnId: "old-transcript", generation: 1))
        precondition(call.turnId == nil, "old STT result")
        precondition(call.apply(.mute(true)) == [.discardInput])
        call.apply(.userSpeechConfirmed)
        precondition(call.generation == 2 && call.input == .muted, "muted input")
        precondition(call.apply(.mute(false)) == [.resetInput])
        precondition(call.apply(.audioRouteChanged).first == .stopOutput && call.generation == 3)
        call.apply(.disconnect)
        precondition(call.lifecycle == .reconnecting && call.output == .idle, "backend disconnect")
        call.apply(.end)
        call.apply(.connected(sessionId: "s1"))
        precondition(call.lifecycle == .idle && call.sessionId == nil, "end during async work")
        call.apply(.start(sessionId: "s3", characterId: "c3"))
        call.apply(.end)
        precondition(call.lifecycle == .idle, "hang up while connecting")
        print("Call reducer lifecycle and cancellation checks passed")
    }
}
