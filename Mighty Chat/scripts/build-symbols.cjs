const fs = require('node:fs');
const path = require('node:path');

// WKWebView treats file-backed CSS masks as cross-origin resources. Embed the
// existing SF Symbol PNGs so local-file and HTTP windows render the same assets.
const source = path.resolve(__dirname, '../Sources');
const symbols = Object.fromEntries(fs.readdirSync(path.join(source, 'Symbols'))
  .filter(name => name.endsWith('.png')).sort().map(name => [
    name.slice(0, -4),
    'data:image/png;base64,' + fs.readFileSync(path.join(source, 'Symbols', name)).toString('base64')
  ]));
fs.writeFileSync(path.join(source, 'symbol-assets.js'),
  '// Generated by scripts/build-symbols.cjs from bundled Symbols PNGs.\n' +
  'window.MIGHTY_SYMBOL_ASSETS = Object.freeze(' + JSON.stringify(symbols) + ');\n');
console.log(`Embedded ${Object.keys(symbols).length} bundled icons for native WebKit.`);
